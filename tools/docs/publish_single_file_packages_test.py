"""
Check that the single-file packages reach the built doc site.

The packages are generated by `//release`, so `mkdocs` doesn't find them in the docs directory the
way it finds the pages: the `hooks:` entry in `mkdocs.yml` copies them in after the build.  Nothing
else would notice if that stopped working --- the site would build and deploy without them, and they
are the only way to get the pre-built packages.
"""

import pathlib
import sys
import tempfile

import mkdocs.commands.build
import mkdocs.config

from publish_single_file_packages import GENERATED_DIR, PACKAGES


def main():
    with tempfile.TemporaryDirectory() as tmp:
        site_dir = pathlib.Path(tmp) / "site"
        config = mkdocs.config.load_config(config_file="mkdocs.yml", site_dir=str(site_dir))
        mkdocs.commands.build.build(config)

        generated = sorted(path.name for path in GENERATED_DIR.glob("*.hh"))
        missing = [name for name in generated if not (site_dir / name).exists()]

    ok = True

    # The hook has to name every package that `//release` generates, or it will quietly skip one.
    if sorted(PACKAGES) != generated:
        ok = False
        print(f"FAIL: the hook publishes {sorted(PACKAGES)}, but `//release` generates {generated}.")

    if missing:
        ok = False
        print(f"FAIL: the built site is missing {missing}.")
        print("  The packages are copied in by the `hooks:` entry in `mkdocs.yml`.")

    if ok:
        print(f"The site has all {len(generated)} single-file packages.")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
