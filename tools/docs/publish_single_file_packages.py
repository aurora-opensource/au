"""
Publish the single-file packages at the root of the doc site.

They are generated by `//release`; this copies them into the site after the build.
"""

import pathlib
import shutil

# The single-file packages, as the `//release` genrules name them.
PACKAGES = [
    "au.hh",
    "au_all_units.hh",
    "au_all_units_noio.hh",
    "au_all_units_stdformat.hh",
    "au_all_units_stdformat_noio.hh",
    "au_noio.hh",
    "au_stdformat.hh",
    "au_stdformat_noio.hh",
]

# Where the genrules put them, relative to the working directory: `bazel run` starts us at the root
# of our runfiles, where the packages appear under their package's path.
GENERATED_DIR = pathlib.Path("release")


def on_post_build(config):
    """Copy each package into the built site.  Raises if one is missing."""
    site_dir = pathlib.Path(config["site_dir"])
    for package in PACKAGES:
        shutil.copy(GENERATED_DIR / package, site_dir / package)
